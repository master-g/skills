CABINET = ('名字形状', '问题开口', '转折', '解答开口', '安慰度')


def draw(rng):
    """{组名: (类型名, 怎么写)}，外加 '候选技能': [三个技能]。"""
    picks = {}
    for group, rows in TABLE.items():
        name, _, how = rng.choices(rows, weights=[w for _, w, _ in rows])[0]
        picks[group] = (name, how)
    picks['候选技能'] = rng.sample(SKILLS, 3)
    return picks


def show(name, how):
    head, _, gloss = name.partition('：')
    notes = '；'.join(x for x in (gloss, how) if x)
    return f'{head}（{notes}）' if notes else head


def render(picks, seed):
    out = [f'种子 {seed}（用 --seed {seed} 复现）', '思维阁']
    out += [f'  {g}：{show(*picks[g])}' for g in CABINET]
    out.append(f'收尾：{show(*picks["收尾"])}')
    out.append(f'候选技能：先看这三个在场景里有没有戏：{"、".join(picks["候选技能"])}，有触发就用，没有就算了')
    fail = picks['失败']
    out.append(f'失败：{show(*fail)}' + ('' if fail[0] == NO_FAILURE else '。失败稀有，短戏可以没有；写就写这一种'))
    return '\n'.join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description='按语料占比抽一组写作约束')
    ap.add_argument('--seed', type=int, help='随机种子；同一个种子抽到同样的结果')
    a = ap.parse_args(argv)
    seed = a.seed if a.seed is not None else random.SystemRandom().randrange(1_000_000)
    print(render(draw(random.Random(seed)), seed))


if __name__ == '__main__':
    main()
